// concatEntry is one line of the concat demuxer list file.
type concatEntry struct {
	path     string
	duration float64
}

// buildConcatList writes the concat demuxer list for a cycle.
//
// Every entry carries an explicit `duration`: the demuxer derives the next
// file's start from the previous file's declared duration, and an inaccurate
// value silently corrupts every later file's timestamps. Declaring them also
// makes the concat output seekable, which is what lets looping work.
func buildConcatList(dir string, items []PlaylistItem, cycle int) (string, error) {
	if len(items) == 0 {
		return "", Errorf(CodePlaylistEmpty, "Playlist tidak berisi video.")
	}
	var sb strings.Builder
	sb.WriteString("# generated by YouTube Live Server; do not edit\n")
	for _, item := range items {
		// The demuxer parses every character after the single-quote as a path, so
		// an embedded quote must be closed, escaped and reopened.
		sb.WriteString("file '")
		sb.WriteString(escapeConcatPath(item.Path))
		sb.WriteString("'\n")
		if item.Duration > 0 {
			sb.WriteString("duration ")
			sb.WriteString(strconv.FormatFloat(item.Duration, 'f', 6, 64))
			sb.WriteByte('\n')
		}
	}
	path := filepath.Join(dir, fmt.Sprintf("playlist-c%d.txt", cycle))
	if err := os.WriteFile(path, []byte(sb.String()), 0o640); err != nil {
		return "", fmt.Errorf("write concat list: %w", err)
	}
	return path, nil
}

func escapeConcatPath(p string) string { return strings.ReplaceAll(p, "'", "'\\''") }

// publisherArgs assembles the FFmpeg command line for one session.
//
// Stream copy is mandatory: FFmpeg moves encoded packets without decoding or
// re-encoding, which is what lets a 2 GB device sustain a live send. The concat
// demuxer opens and closes each input file internally, so the FLV muxer and the
// RTMPS connection are created exactly once and never re-established at a file
// boundary (FR-06).
func publisherArgs(ffmpeg, listPath, outputURL string, loop bool) []string {
	args := []string{
		"-nostdin",
		"-hide_banner",
		"-loglevel", "warning",
		// A short stats period keeps the stall detector responsive without
		// flooding the log.
		"-stats_period", "0.5",
		"-progress", "pipe:1",
		// Read at native frame rate: a live send must be paced in real time.
		"-re",
	}
	if loop {
		// Re-reading the concat list keeps the destination connection open
		// across cycle boundaries.
		args = append(args, "-stream_loop", "-1")
	}
	args = append(args,
		"-f", "concat",
		"-safe", "0",
		"-i", listPath,
		"-map", "0:v:0",
		"-map", "0:a:0",
		"-c:v", "copy",
		"-c:a", "copy",
		// MP4 stores AAC without ADTS headers; the FLV muxer needs them, and its
		// automatic detection only fires for sources that carry a syncword.
		"-bsf:a", "aac_adtstoasc",
		// ffmpeg exposes no reconnect options for rtmps, so a wedged connection
		// is bounded here and the worker restarts the process instead. Keepalive
		// is left to the OS: the rtmp protocol handler has no tcp_keepalive
		// option, and passing one makes ffmpeg refuse to start.
		"-rw_timeout", "15000000",
		"-f", "flv",
		outputURL,
	)
	return args
}

// Attempt is one run of the FFmpeg process.
type Attempt struct {
	cmd     *exec.Cmd
	started time.Time

	// outTimeUs is the media timestamp most recently reported by -progress.
	outTimeUs  atomic.Int64
	lastGrowMs atomic.Int64
}

// publisher owns one FFmpeg process for the lifetime of a cycle.
type publisher struct {
	bin     string
	log     *logging.Logger
	session string

	mu      sync.Mutex
	current *Attempt
}

// start launches FFmpeg. The caller owns the returned Attempt.
func (p *publisher) start(ctx context.Context, listPath, outputURL string, loop bool) (*Attempt, error) {
	args := publisherArgs(p.bin, listPath, outputURL, loop)
	cmd := exec.Command(p.bin, args...)
	// A dedicated process group lets Stop reach FFmpeg and anything it spawns.
	setProcessGroup(cmd)

	stdout, err := cmd.StdoutPipe()
	if err != nil {
		return nil, err
	}
	stderr, err := cmd.StderrPipe()
	if err != nil {
		return nil, err
	}
	// FFmpeg reads stdin by default; closing it prevents it from swallowing the
	// server's own stdin.
	cmd.Stdin = nil

	if err := cmd.Start(); err != nil {
		return nil, fmt.Errorf("start ffmpeg: %w", err)
	}

	att := &Attempt{cmd: cmd, started: time.Now()}
	att.lastGrowMs.Store(time.Now().UnixMilli())

	go readProgress(att, stdout, p.log, p.session)
	go readStderr(stderr, p.log, p.session)

	p.mu.Lock()
	p.current = att
	p.mu.Unlock()

	p.log.Info(logging.SourcePublisher, p.session,
		"FFmpeg dijalankan (pid %d) untuk %s", cmd.Process.Pid, filepath.Base(listPath))
	return att, nil
}

// progress reads `-progress` output. Keys arrive as key=value pairs terminated
// by a `progress=continue|end` line.
func readProgress(att *Attempt, r io.Reader, log *logging.Logger, session string) {
	scanner := bufio.NewScanner(r)
	scanner.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	lastLog := time.Time{}
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		key, value, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		switch key {
		case "out_time_us", "out_time":
			if us, ok := parseOutTime(value); ok {
				att.outTimeUs.Store(us)
				att.lastGrowMs.Store(time.Now().UnixMilli())
			}
		case "frame":
			if time.Since(lastLog) > 10*time.Second {
				lastLog = time.Now()
				log.Debug(logging.SourcePublisher, session, "progress frame=%s", value)
			}
		case "speed":
			if time.Since(lastLog) > 30*time.Second {
				lastLog = time.Now()
				log.Debug(logging.SourcePublisher, session, "speed=%s", value)
			}
		case "progress":
			if value == "end" {
				return
			}
		}
	}
	if err := scanner.Err(); err != nil && !errors.Is(err, context.Canceled) {
		log.Debug(logging.SourcePublisher, session, "progress reader ended: %v", err)
	}
}

// parseOutTime converts FFmpeg's progress values into microseconds.
// out_time_us may carry a decimal part; out_time is HH:MM:SS.microseconds.
func parseOutTime(value string) (int64, bool) {
	if value == "N/A" {
		return 0, false
	}
	if us, err := strconv.ParseFloat(value, 64); err == nil {
		return int64(us), true
	}
	neg := strings.HasPrefix(value, "-")
	parts := strings.Split(strings.TrimPrefix(value, "-"), ":")
	if len(parts) != 3 {
		return 0, false
	}
	h, err1 := strconv.ParseFloat(parts[0], 64)
	m, err2 := strconv.ParseFloat(parts[1], 64)
	s, err3 := strconv.ParseFloat(parts[2], 64)
	if err1 != nil || err2 != nil || err3 != nil {
		return 0, false
	}
	total := (h*3600 + m*60 + s) * 1e6
	if neg {
		total = -total
	}
	return int64(total), true
}

// readStderr forwards FFmpeg warnings into the application log.
func readStderr(r io.Reader, log *logging.Logger, session string) {
	scanner := bufio.NewScanner(r)
	scanner.Buffer(make([]byte, 0, 64*1024), 256*1024)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" {
			continue
		}
		lower := strings.ToLower(line)
		switch {
		case strings.Contains(lower, "non-monotonic"):
			// Timestamp discontinuity is the failure mode that silently corrupts
			// a stream, so it is surfaced rather than swallowed.
			log.Warn(logging.SourcePublisher, session, "FFmpeg: %s", line)
		case strings.Contains(lower, "error"), strings.Contains(lower, "invalid"),
			strings.Contains(lower, "failed"), strings.Contains(lower, "unable"):
			log.Warn(logging.SourcePublisher, session, "FFmpeg: %s", line)
		default:
			log.Debug(logging.SourcePublisher, session, "FFmpeg: %s", line)
		}
	}
}

// wait blocks until the process exits and returns its exit code.
//
// Values outside 0-255 come from the signal and NTSTATUS spaces and mean
// nothing to an operator, so they are folded onto 255, FFmpeg's own generic
// failure code.
func (a *Attempt) wait() (int, error) {
	err := a.cmd.Wait()
	var exitErr *exec.ExitError
	if errors.As(err, &exitErr) {
		code := exitErr.ExitCode()
		if code < 0 || code > 255 {
			return 255, nil
		}
		return code, nil
	}
	if err != nil {
		return -1, err
	}
	return 0, nil
}

// outTimeSeconds is the media time sent so far, in seconds.
func (a *Attempt) outTimeSeconds() float64 { return float64(a.outTimeUs.Load()) / 1e6 }

// stalledFor reports how long media time has failed to advance.
func (a *Attempt) stalledFor() time.Duration {
	last := a.lastGrowMs.Load()
	if last == 0 {
		return 0
	}
	return time.Since(time.UnixMilli(last))
}

// stop asks FFmpeg to shut down cleanly, escalating if it refuses.
//
// FFmpeg installs the same handler for SIGINT and SIGTERM; either unblocks the
// network read, drains the muxer and sends FCUnpublish so YouTube sees a clean
// end of broadcast. SIGKILL cannot do that, so it is only a last resort.
func (a *Attempt) stop(grace time.Duration, log *logging.Logger, session string) {
	if a.cmd == nil || a.cmd.Process == nil {
		return
	}
	pid := processID(a.cmd)
	_ = signalInterrupt(a.cmd)
	deadline := time.Now().Add(grace)
	for time.Now().Before(deadline) {
		if !processAlive(a.cmd) {
			return
		}
		time.Sleep(100 * time.Millisecond)
	}
	log.Warn(logging.SourcePublisher, session,
		"FFmpeg (pid %d) tidak berhenti dalam %s, dihentikan paksa", pid, grace)
	_ = signalKill(a.cmd)
}
